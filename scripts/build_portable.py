"""Build the Windows x64 community ZIP from public allowlisted inputs and hash-pinned packages."""
import argparse
import concurrent.futures
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import sys
import tarfile
import tempfile
from urllib.request import urlopen
import zipfile

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "packaging"
NAME = "H3 Creative Studio"
RUNTIME_URL = ("https://github.com/astral-sh/python-build-standalone/releases/download/20261124/"
               "cpython-3.11.18%2B20261124-x86_64-pc-windows-msvc-install_only.tar.gz")
RUNTIME_HASH = "3e4a35e3c238e5090d36bf95c041d9052bc82d6e298cb912ba7f70f6c66cf81a"
NOTICES = ("runtime-libraries.txt", "WebView2-LICENSE.txt", "WebView2-NOTICE.txt", "proxy-tools-LICENSE.txt", "GPL-3.0.txt",
           "LGPL-3.0.txt", "GPL-2.0.txt", "LGPL-2.1.txt", "codec-sources.txt")


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def public_artifact(cache, name, url, expected):
    path = cache / name
    if not path.exists():
        with tempfile.NamedTemporaryFile(dir=cache, delete=False) as output:
            work = Path(output.name)
            try:
                with urlopen(url, timeout=90) as source:
                    shutil.copyfileobj(source, output)
            except BaseException:
                output.close()
                work.unlink(missing_ok=True)
                raise
        try:
            if digest(work) != expected:
                raise ValueError("Download failed SHA-256 verification for " + name)
            os.replace(work, path)
        finally:
            work.unlink(missing_ok=True)
    elif digest(path) != expected:
        raise ValueError("Cached file differs from upstream digest. Move it aside and rebuild: " + str(path))
    return path


def extract_runtime(archive, dest):
    # Exclude debug symbols, development headers and generated bytecode. Retain the distribution licences.
    with tarfile.open(archive) as tar:
        for entry in tar:
            parts = PurePosixPath(entry.name).parts
            if not parts or parts[0] != "python" or ".." in parts or any(":" in p for p in parts):
                raise ValueError("Unexpected Python archive entry.")
            if (not entry.isfile() or entry.name.endswith((".pdb", ".pyc", ".lib")) or "__pycache__" in parts
                    or parts[1:2] in (("include",), ("Scripts",)) or parts[1:3] == ("Lib", "test")):
                continue
            target = dest.joinpath(*parts[1:])
            target.parent.mkdir(exist_ok=True, parents=True)
            with tar.extractfile(entry) as content, target.open("wb") as out:
                shutil.copyfileobj(content, out)


def install_dependencies(wheels, stage, packages):
    runtime = stage / "runtime"
    with tempfile.TemporaryDirectory() as temp:
        wheelhouse = Path(temp)
        for src in wheels:
            if src.name.endswith(".whl"):
                try:
                    os.link(src,wheelhouse/src.name)
                except OSError:
                    shutil.copyfile(src,wheelhouse/src.name)
            else:
                # proxy_tools ships a pure-Python source distribution. Build only the verified archive.
                subprocess.run([sys.executable, "-m", "pip", "--isolated", "wheel", "--no-deps", "--no-index",
                                "--no-build-isolation", "--disable-pip-version-check", "-w", temp, str(src)], check=True)
        command = [str(runtime / "python.exe"), "-EsB", "-m", "pip", "--isolated", "install", "--no-index",
                   "--disable-pip-version-check", "--no-compile", "--no-deps", "--only-binary=:all:", "--find-links", temp]
        command.extend(p["name"]+"=="+p["version"] for p in packages)
        subprocess.run(command, check=True)
    # Console entry points reference temporary build paths. Studio only imports these distributions.
    scripts = runtime / "Scripts"
    if scripts.exists():
        for entry in scripts.iterdir():
            if entry.is_file(): entry.unlink()
    for module in (runtime/"Lib"/"site-packages"/"cv2").glob("opencv_videoio_ffmpeg*.dll"):
        module.unlink()  # All Studio video I/O uses PyAV or the user's FFmpeg executable.


def sources(stage):
    allowlist = (ROOT / "SOURCE_ALLOWLIST.txt").read_text("utf-8-sig").splitlines()
    for name in allowlist:
        path = PurePosixPath(name)
        if path.is_absolute() or ".." in path.parts: raise ValueError("Invalid source allowlist entry")
        if not (name in ("studio.py","requirements.txt","LICENSE","README.md","THIRD_PARTY_NOTICES.md")
                or name.startswith(("h3studio/","vendor/","docs/"))): continue
        dest = stage / "app" / name
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / name, dest)
    for required in ("app/h3studio/web/shell.js","app/h3studio/web/cut.js","app/h3studio/cut.py"):
        if not (stage / required).is_file(): raise ValueError(required + " is missing from the public source allowlist.")


def native_launcher(stage):
    compiler = Path(os.environ["WINDIR"])/"Microsoft.NET/Framework64/v4.0.30319/csc.exe"
    if not compiler.is_file():raise FileNotFoundError("Install the .NET Framework 4.x Windows x64 compiler.")
    from PIL import Image, ImageDraw
    art=Image.new("RGBA",(256,256),(19,25,25,255))
    draw=ImageDraw.Draw(art)
    for box in [(36,64,55,186),(88,64,107,186),(36,114,107,134),(137,64,207,83),
                (188,64,207,186),(137,114,207,134),(137,167,207,186)]:
        draw.rectangle(box,fill=(231,241,237) if box[0]<120 else (137,224,179))
    with tempfile.TemporaryDirectory() as temp:
        icon=Path(temp)/"studio.ico"
        art.save(icon,sizes=[(16,16),(32,32),(48,48),(128,128),(256,256)])
        subprocess.run([str(compiler),"/nologo","/optimize+","/target:winexe","/platform:x64",
                        "/r:System.Windows.Forms.dll","/r:Microsoft.CSharp.dll",
                        "/win32icon:"+str(icon),"/out:"+str(stage/(NAME+".exe")),str(PACK/"Launcher.cs")],check=True)


def build(output,cache):
    packages=json.loads((PACK/"windows-dependencies.json").read_text("utf-8"))
    pins={p["name"].lower().replace("_","-")+"=="+p["version"] for p in packages}
    if not set(s.lower().replace("_","-") for s in (ROOT/"requirements.txt").read_text().splitlines() if s.strip())<=pins:
        raise ValueError("Refresh the Windows dependency lock for the current requirements.")
    cache.mkdir(parents=True, exist_ok=True)
    runtime = public_artifact(cache,"python-3.11.18.tar.gz",RUNTIME_URL,RUNTIME_HASH)
    with concurrent.futures.ThreadPoolExecutor(max_workers=5) as pool:
        wheels=list(pool.map(lambda p:public_artifact(cache,p["filename"],p["url"],p["sha256"]),packages))
    output.parent.mkdir(parents=True,exist_ok=True)
    with tempfile.TemporaryDirectory(dir=output.parent) as working:
        stage=Path(working)/NAME
        stage.mkdir()
        sources(stage)
        extract_runtime(runtime,stage/"runtime")
        install_dependencies(wheels,stage,packages)
        native_launcher(stage)
        shutil.copyfile(PACK/"PORTABLE.md",stage/"Getting started.md")
        notice=stage/"notices"
        notice.mkdir()
        for name in NOTICES:shutil.copyfile(PACK/"notices"/name,notice/name)
        shutil.copyfile(PACK/"windows-dependencies.json",notice/"windows-dependencies.json")
        shutil.copyfile(PACK/"RUNTIME-NOTICES.md",notice/"RUNTIME-NOTICES.md")
        (stage/"Create desktop shortcut.cmd").write_bytes(b'@echo off\r\nstart "" "%~dp0H3 Creative Studio.exe" --create-shortcut\r\n')
        python=stage/"runtime/python.exe"
        subprocess.run([str(python),"-EsB","-c","import av,cv2,httpx,numpy,PIL,psutil,webview,clr; from h3studio.application import Studio"],cwd=stage/"app",check=True)
        subprocess.run([str(python),"-EsB","-m","pip","check"],check=True)
        archive=Path(working)/"release.zip"
        with zipfile.ZipFile(archive,"w",compression=zipfile.ZIP_DEFLATED,compresslevel=6) as out:
            for p in sorted(stage.rglob("*")):
                if p.is_file() and "__pycache__" not in p.parts and p.suffix!=".pyc":
                    out.write(p,p.relative_to(stage.parent))
        with zipfile.ZipFile(archive) as z:
            bad=z.testzip()
            if bad:raise ValueError("ZIP verification failed for "+bad)
        os.replace(archive,output)
    print(f"{output}  {digest(output)}  ({output.stat().st_size:,} bytes)")


if __name__=="__main__":
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output",type=Path,default=ROOT/"dist/H3-Creative-Studio-2.0.0-Windows-x64.zip")
    parser.add_argument("--cache",type=Path,default=ROOT/".local/release-cache")
    opts=parser.parse_args()
    build(opts.output.resolve(),opts.cache.resolve())
